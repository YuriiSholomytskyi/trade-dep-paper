"""Referee-response addenda for the demand horse race (all on the full negative cycle).

Three quantities the referee asked for, computed on the same estimation sample and specification
as the full-cycle column of Table~\\ref{tab:main}:

  1. Wald test of H0: beta_US = beta_OtherAdvanced (does the US coefficient actually differ from
     the other-advanced coefficient, not merely "significant vs insignificant"?).
  2. Equal-country-weight (inverse-number-of-episodes) re-estimation, so countries with many
     episodes (Costa Rica, 29) do not dominate the point estimate.
  3. Standardized and interquartile effect sizes for the US-demand pull.

Prints the numbers and writes a short LaTeX snippet fragment to output/addendum_numbers.tex
(plain \\newcommand macros the paper can \\input and cite in footnotes).
Run: python scripts/referee_addendum.py
"""
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, os.path.dirname(__file__))
from build_horserace_hp import build_episodes  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "output")
XS = ["us_pull", "otheradv_pull", "emer_pull", "china_pull", "trade_open", "depth_gap", "program"]


def ols_full(d, y, xs, cluster="iso3", w=None):
    """OLS/WLS with cluster-robust vcov; returns names, b, V (full matrix), n, G."""
    d = d.dropna(subset=[y] + xs + [cluster])
    X = np.column_stack([np.ones(len(d))] + [d[x].values.astype(float) for x in xs])
    yv = d[y].values.astype(float)
    names = ["const"] + xs
    wv = np.ones(len(d)) if w is None else d[w].values.astype(float)
    W = wv / wv.mean()                      # scale-normalize (does not move point estimates)
    XtWX_inv = np.linalg.inv((X * W[:, None]).T @ X)
    b = XtWX_inv @ ((X * W[:, None]).T @ yv)
    u = yv - X @ b
    groups = d[cluster].values
    meat = np.zeros((X.shape[1], X.shape[1]))
    for g in np.unique(groups):
        m = groups == g
        s = (X[m] * W[m, None]).T @ u[m]
        meat += np.outer(s, s)
    G, n, k = len(np.unique(groups)), len(d), X.shape[1]
    corr = (G / (G - 1)) * ((n - 1) / (n - k))
    V = corr * XtWX_inv @ meat @ XtWX_inv
    return names, b, V, n, G


def main():
    ep = build_episodes()

    # ---- 1. Wald test beta_US = beta_OtherAdvanced on the full cycle ----
    names, b, V, n, G = ols_full(ep, "t_full", XS)
    idx = {nm: i for i, nm in enumerate(names)}
    R = np.zeros(len(names))
    R[idx["us_pull"]] = 1.0
    R[idx["otheradv_pull"]] = -1.0
    diff = float(R @ b)
    se_diff = float(np.sqrt(R @ V @ R))
    t_diff = diff / se_diff
    df = G - 1                                   # cluster-count degrees of freedom
    p_diff = 2 * stats.t.sf(abs(t_diff), df)
    b_us, b_oa = b[idx["us_pull"]], b[idx["otheradv_pull"]]

    print("=== 1. Wald test  H0: beta_US = beta_OtherAdvanced  (full cycle) ===")
    print(f"beta_US={b_us:.2f}  beta_OA={b_oa:.2f}  diff={diff:.2f}  se(diff)={se_diff:.2f}")
    print(f"t={t_diff:.2f}  df={df}  p={p_diff:.3f}  (n={n}, clusters={G})")

    # ---- 2. Equal-country-weight (inverse number of episodes per country) ----
    epw = ep.copy()
    cnt = epw.groupby("iso3").iso3.transform("size")
    epw["cw"] = 1.0 / cnt
    _, bw, Vw, nw, Gw = ols_full(epw, "t_full", XS, w="cw")
    bw_us = bw[idx["us_pull"]]
    tw_us = bw_us / np.sqrt(Vw[idx["us_pull"], idx["us_pull"]])
    print("\n=== 2. Equal-country-weight (inverse-episode) full cycle ===")
    max_ep = int(ep.groupby("iso3").size().max())
    max_iso = ep.groupby("iso3").size().idxmax()
    print(f"most-frequent country: {max_iso} with {max_ep} episodes")
    print(f"US pull beta={bw_us:.2f} (t={tw_us:.1f})  vs baseline {b_us:.2f}")

    # ---- 3. Standardized and interquartile effect sizes (US pull, full cycle) ----
    est = ep.dropna(subset=["t_full"] + XS + ["iso3"])
    sx, sy = est.us_pull.std(), est.t_full.std()
    q1, q3 = est.us_pull.quantile([0.25, 0.75])
    iqr = q3 - q1
    std_effect = b_us * sx / sy                  # SD-of-y per SD-of-x
    iqr_effect = b_us * iqr                       # months per interquartile move
    print("\n=== 3. Effect sizes (US pull, full cycle) ===")
    print(f"sd(us_pull)={sx:.2f}  IQR(us_pull)={iqr:.2f}  sd(t_full)={sy:.1f}")
    print(f"standardized: {std_effect:.2f} sd  |  interquartile: {iqr_effect:.1f} months")

    # ---- LaTeX macros ----
    def m(name, val):
        return rf"\newcommand{{\{name}}}{{{val}}}"
    tex = [
        "% auto-generated by scripts/referee_addendum.py -- referee-response numbers",
        m("WaldDiff", f"{diff:.1f}"),
        m("WaldSe", f"{se_diff:.1f}"),
        m("WaldT", f"{t_diff:.1f}"),
        m("WaldP", f"{p_diff:.2f}"),
        m("EqwUS", f"{bw_us:.1f}"),
        m("EqwT", f"{tw_us:.1f}"),
        m("MaxEpN", f"{max_ep}"),
        m("MaxEpIso", f"{max_iso}"),
        m("UsIqr", f"{iqr:.1f}"),
        m("UsIqrEffect", f"{abs(iqr_effect):.1f}"),
        m("UsStdEffect", f"{abs(std_effect):.2f}"),
    ]
    with open(os.path.join(OUT, "addendum_numbers.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(tex) + "\n")
    print("\nsaved output/addendum_numbers.tex")


if __name__ == "__main__":
    main()
